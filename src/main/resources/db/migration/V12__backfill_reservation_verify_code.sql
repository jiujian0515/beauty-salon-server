-- ============================================================
-- V12：为历史预约补生成核销码
--
-- V11 之前创建的预约单 verify_code 为 NULL，无法核销。
-- 这里按 id 做确定性映射生成 6 位码：
--   code = (id * 7919 + 104729) % 1000000
-- 7919 与 1000000 互质，id 相差不足 100 万时不会重复，
-- 可满足 uk_merchant_verify_code 的唯一约束；
-- 之后新建的预约仍由程序生成随机核销码。
-- ============================================================

UPDATE reservation
SET verify_code = LPAD((id * 7919 + 104729) % 1000000, 6, '0')
WHERE verify_code IS NULL;
